#!/usr/bin/env python3
"""Write the realistic study's random gateway layouts (PLAN_REALISTIC sect 3, site RAND), once, seeded.

Ad hoc sites put gateways where it was convenient: here, uniformly inside the inner 80 % of the 10 km x 10 km box, no
two closer than 1000 m (OURS). Ten layouts each for 3 and 5 gateways. Re-running reproduces the same files exactly;
they are committed and never regenerated by a campaign.
usage: make_realistic_layouts.py [outdir]   (default scripts/layouts/realistic)
"""
import os
import random
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "layouts", "realistic")
HALF, INNER, MIN_SEP = 5000.0, 0.8, 1000.0
os.makedirs(OUT, exist_ok=True)
for n in (3, 5):
    for k in range(10):
        rng = random.Random(1000 * n + k)
        pts = []
        while len(pts) < n:
            p = (rng.uniform(-INNER * HALF, INNER * HALF), rng.uniform(-INNER * HALF, INNER * HALF))
            if all(((p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2) ** 0.5 >= MIN_SEP for q in pts):
                pts.append(p)
        with open(os.path.join(OUT, f"rand_n{n}_k{k}.csv"), "w") as f:
            f.write(f"# realistic study, site RAND: {n} gateways, layout {k}, seed {1000 * n + k} (make_realistic_layouts.py)\nx,y\n")
            for x, y in pts:
                f.write(f"{x:.1f},{y:.1f}\n")
print(f"wrote 20 layouts to {OUT}")
