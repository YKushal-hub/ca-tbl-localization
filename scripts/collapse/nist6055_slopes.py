# Evaluates the NISTIR 6055 Table 4.4a/b/d regression polynomials (plain concrete batch 1)
# and the per-metre slope between the 101.6 mm and 304.8 mm specimens. Rows NIST6055-*.
import math
def p(c,F): return sum(m*F**i for i,m in enumerate(c))
lo_db={'102':[-7.9286,0.53499,-12.311,9.3891,-0.84422,-1.4187,0.39117],
       '203':[-19.516,12.151,-43.788,47.941,-25.801,6.5042,-0.57868],
       '305':[-19.320,-27.660,-30.002,105.78,-94.379,35.923,-5.1097]}
lo_dec={'102':[0.42829,-0.12022,-0.32189,0.41577,-0.18072,0.022805,0.0018124],
        '203':[0.12864,0.032106,-0.33455,0.45016,-0.28115,0.084769,-0.0098875],
        '305':[0.074321,-0.17565,0.17475,-0.028414,-0.052759,0.031249,-0.0052285]}
hi_db={'102':[33.110,-88.319,53.943,-16.053,2.0035,0.13960,-0.084168,0.012014,-7.9082e-4,2.0626e-5],
       '203':[168.11,-328.42,206.89,-66.763,10.358,-0.074879,-0.25409,0.043347,-3.1547e-3,8.9365e-5],
       '305':[67.802,-227.97,146.18,-46.098,6.1910,0.39922,-0.27700,0.0427,-3.0410e-3,8.6331e-5]}
th={'102':0.1016,'203':0.2032,'305':0.3048}
for F in [0.868,1.0,1.5,2.0]:
    d={k:p(v,F) for k,v in lo_db.items()}; t={k:p(v,F) for k,v in lo_dec.items()}
    chk={k:(10*math.log10(t[k]) if t[k]>0 else float('nan')) for k in t}
    sl=(d['102']-d['305'])/(0.3048-0.1016)
    print(f"F={F}: dB {d}  10log10(dec) {chk}  slope(102->305) {sl:.2f} dB/m")
for F in [3.0,4.0,6.5,8.0]:
    d={k:p(v,F) for k,v in hi_db.items()}
    sl=(d['102']-d['305'])/(0.3048-0.1016)
    print(f"F={F}: dB {d} slope {sl:.2f} dB/m")
