#!/usr/bin/env python3
"""D6 - document/number reconciliation.

Attempts to reproduce numeric claims from the directory each document cites.
Only claims whose source is mechanically identifiable are attempted; the rest are
reported UNREPRODUCIBLE-BY-THIS-TOOL rather than silently omitted.
"""
import csv, glob, os, re, statistics as st

A, R, CYC = 0.95, 25.0, 1440

def arm_rows(d):
    out = {}
    for f in glob.glob(os.path.join(d, "**", "arm_summary.csv"), recursive=True):
        for r in csv.DictReader(open(f)):
            out.setdefault(r["arm"], []).append(r)
    return out

def mean_of(d, arm, col):
    rows = arm_rows(d).get(arm, [])
    vals = []
    for r in rows:
        try: vals.append(float(r[col]))
        except (ValueError, KeyError): pass
    return (st.mean(vals), len(vals)) if vals else (None, 0)

print("# D6 — document / number reconciliation\n")
print("| claim | document | cited dir | published | reproduced | verdict |")
print("|---|---|---|---|---|---|")

checks = [
  ("trig_precision", "Simulation.md/ledger", "results/p10_plane_fix", 0.9343,
   lambda: mean_of("results/p10_plane_fix", "ca_tbl_full", "trig_precision")),
  ("trig_recall", "Simulation.md/ledger", "results/p10_plane_fix", 0.7041,
   lambda: mean_of("results/p10_plane_fix", "ca_tbl_full", "trig_recall")),
  ("ca_tbl_full totalJ", "report §1.3", "results/p10_plane_fix", 24.26,
   lambda: mean_of("results/p10_plane_fix", "ca_tbl_full", "totalJ")),
]
findings = 0
for name, doc, d, pub, fn in checks:
    if not os.path.isdir(d):
        print("| %s | %s | `%s` | %s | — | **UNREPRODUCIBLE (dir absent)** |" % (name, doc, d, pub))
        findings += 1; continue
    v, n = fn()
    if v is None:
        print("| %s | %s | `%s` | %s | — | **UNREPRODUCIBLE (column absent)** |" % (name, doc, d, pub))
        findings += 1; continue
    ok = abs(v - pub) <= max(0.0005, abs(pub) * 0.002)
    if not ok: findings += 1
    print("| %s | %s | `%s` | %.4f | %.4f (n=%d) | %s |"
          % (name, doc, d, pub, v, n, "MATCH" if ok else "**MISMATCH**"))

print("\n## r80 = 909.5 m, quoted in three documents\n")
for doc, pat in (("Architecture.md", r"909\.5"),
                 ("CA-TBL_Technical_Report_SelfContained.md", r"909\.5"),
                 ("CA_TBL_SIMULATION_REPORT.md", r"909\.5")):
    if not os.path.exists(doc): continue
    for i, line in enumerate(open(doc, errors="replace"), 1):
        if re.search(pat, line):
            print("- `%s:%d` still quotes 909.5 m — measured post-D1 value is **1149.5 m**. **MISMATCH**" % (doc, i))
            findings += 1
            break

print("\n## Claims not mechanically checkable by this tool\n")
print("- prose claims without a cited results directory")
print("- figures generated by `scripts/make_report_figures.py` (reads `results/probe_audit/`)")
print("- any claim whose population is not stated in the document")
print("\nThese are reported as gaps, not as matches.")
print("\nSTATUS: %s" % ("FINDING" if findings else "OK"))
